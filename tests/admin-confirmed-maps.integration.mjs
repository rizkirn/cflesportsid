import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {html,post,fields,create,smallFixture} from './admin-http-fixture.mjs';
import {remainingVetoMaps} from '../src/utils/veto-engine.mjs';

const readonly=page=>{assert.doesNotMatch(page,/data-confirm-maps|data-official="true"|id="match-data"/);assert.match(page,/Confirmed/);};
const root=await create(`Confirmed Maps ${crypto.randomUUID()}`,8);
const round=root+'/maps?round=quarter-final';
let page=await html(round);let form=fields(page);
const pool=JSON.parse(page.match(/data-maps="([^"]+)"/)[1].replaceAll('&quot;','"').replaceAll('&amp;','&'));
const maps=pool.slice(0,3).map(map=>map.id);
form.set('maps',JSON.stringify(maps));form.set('actions','[]');
await post(round,form);
page=await html(root+'/maps');assert.match(page,/View Randomizer Result/);assert.match(page,/Redo Randomizer/);assert.doesNotMatch(page,/data-confirm-maps/);
const official=await html(round);readonly(official);
page=await html(round+'&redo=1');assert.match(page,/Cancel Redo/);assert.match(page,/data-confirm-maps/);
readonly(await html(round));assert.equal(await html(round),official);
form=fields(page);form.set('maps',JSON.stringify([maps[0],maps[0],maps[2]]));form.set('actions','[]');await post(round+'&redo=1',form,400);
assert.equal(await html(round),official);
const replacement=pool.slice(3,6).map(map=>map.id);form.set('maps',JSON.stringify(replacement));await post(round+'&redo=1',form);
readonly(await html(round));assert.notEqual(await html(round),official);
await post(round+'&redo=1',form,409);

const fixture=await smallFixture();const match=fixture.matches[0];const veto=fixture.root+'/maps?match='+match;
page=await html(fixture.root+'/maps');assert.match(page,/View Veto/);assert.match(page,/Redo Veto/);
const confirmed=await html(veto);readonly(confirmed);assert.match(confirmed,/Veto History/);assert.match(confirmed,/Ban/);assert.match(confirmed,/Pick/);
page=await html(veto+'&redo=1');assert.match(page,/Cancel Redo/);assert.match(page,/id="match-data"/);
assert.equal(await html(veto),confirmed);
const config=JSON.parse(page.match(/id="match-data"[^>]*>([\s\S]*?)<\/script>/)[1])[0].veto;
const actions=[];for(const step of config.steps)actions.push({...step,map:remainingVetoMaps(config.maps.map(map=>map.id),actions).at(-1),voided:false});
const picked=['A','B'].map(team=>actions.find(action=>action.team===team&&action.action==='pick').map);picked.push(remainingVetoMaps(config.maps.map(map=>map.id),actions)[0]);
form=fields(page);form.set('maps',JSON.stringify(picked));form.set('actions',JSON.stringify(actions));
const saved=await post(veto+'&redo=1',form);assert.equal(saved.headers.get('location'),fixture.root+'/maps?saved=1');
readonly(await html(veto));assert.notEqual(await html(veto),confirmed);
assert.match(await html(fixture.root+'/maps?saved=1'),/Official maps saved/);
const result=fixture.root+'/bracket?match='+match;form=fields(await html(result));form.set('intent','edit-result');form.set('result_type','played');form.set('score1','2');form.set('score2','1');form.set('confirmed','yes');await post(result,form);
page=await html(veto);readonly(page);assert.doesNotMatch(page,/>Redo Veto</);assert.match(page,/Maps are locked/);
readonly(await html(veto+'&redo=1'));
writeFileSync('/private/tmp/cfl-confirmed-maps-fixture.json',JSON.stringify({root:fixture.root,match,roundRoot:root,round}));
console.log('Confirmed maps HTTP: overview, read-only history, redo/cancel, invalid/stale replacement, successful replacement and play locks passed.');
